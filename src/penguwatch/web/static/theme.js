// This browser's theme and light/dark mode, on <html> before the page is drawn: a classic script in <head> (no module, no
// import), so it runs before the first paint and the page never flashes the wrong theme (docs/themes.md, "How the page
// applies a theme"). The sign-in page loads it too.
//
// The server writes the default theme (the Display > Theme setting, display.theme) as <html data-look-default> and the themes it has as
// data-looks ([{id, name, modes, css, skin, effect}]); the sign-in page has neither, so there only the mode applies. This browser's own
// choices, made in the header's theme menu (js/themes.js), are in localStorage: `penguwatch.look` (a theme id; none: the
// server's default) and `penguwatch.mode` (light or dark; none: the system's). A theme with one mode forces it.
//
// Before themes, the header button kept "light" or "dark" in `penguwatch.theme`. That key is read once: its value becomes the
// mode, the theme stays unset (so the server's default applies), and the old key is removed.
//
// The script sits after the page's shared stylesheets: it writes the links to the theme's stylesheet (`css`: its token
// blocks, generated by the server) and its skin (`skin`: skin.css, shapes and textures) where it stands, so the browser
// waits for those sheets before the first paint as for the others, and only the theme in use is loaded. js/themes.js links
// another theme's on a switch, and starts the theme's effect (`effect`), which nothing here runs.
(function () {
  var root = document.documentElement;
  var read = function (key) {
    try { return localStorage.getItem(key) || ''; } catch (e) { return ''; }
  };
  var write = function (key, value) {
    try { if (value) localStorage.setItem(key, value); else localStorage.removeItem(key); } catch (e) { /* not kept */ }
  };
  var old = read('penguwatch.theme');
  if (old) {
    if ((old === 'light' || old === 'dark') && !read('penguwatch.mode')) write('penguwatch.mode', old);
    write('penguwatch.theme', '');
  }
  // a theme's stylesheet is ours, under /static/v/<version>/themes/ (penguwatch.web.themes.page_list): anything else in
  // the list is never linked
  var ours = function (url) {
    return typeof url === 'string' && /^\/static\/v\/[\w-]+\/themes\/[\w-]+\/[\w-]+\.css$/.test(url);
  };
  var looks = [];
  try { looks = JSON.parse(root.getAttribute('data-looks') || '[]'); } catch (e) { looks = []; }
  var find = function (id) {
    for (var i = 0; i < looks.length; i++) if (looks[i] && looks[i].id === id) return looks[i];
    return null;
  };
  var look = find(read('penguwatch.look')) || find(root.getAttribute('data-look-default')) || find('default');
  var mode = read('penguwatch.mode');
  if (look && look.modes && look.modes.length === 1) mode = look.modes[0];
  if (mode === 'light' || mode === 'dark') root.setAttribute('data-theme', mode);
  else root.removeAttribute('data-theme');
  if (!look) return;
  root.setAttribute('data-look', look.id);
  // written by the parser, not appended: a parser-made stylesheet holds the first paint until it is loaded
  var sheet = function (url, mark) {
    if (!ours(url)) return;
    var link = document.createElement('link');
    link.rel = 'stylesheet';
    link.href = url;
    link.setAttribute(mark, look.id);
    document.write(link.outerHTML);
  };
  sheet(look.css, 'data-look-css'); // the token blocks first,
  sheet(look.skin, 'data-look-skin'); // then the skin, which reads them
})();
